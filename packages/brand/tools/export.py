"""Write the Folio brand files and Android launcher resources.

Usage: python export.py <repo root>
Needs rsvg-convert on PATH, Pillow, and fontTools (only for the wordmark).
The chosen concept is B: white brush F with an ink dot on the sage accent.
"""
import os, subprocess, sys, tempfile
from PIL import Image
from concepts import CONCEPTS, SAGE, INK, WHITE, svg, mark_paths

ROOT = sys.argv[1]
BRAND = os.path.join(ROOT, "packages/brand")
RES = os.path.join(ROOT, "apps/mobile/androidApp/src/main/res")
CHOSEN = "B"
FONT = os.environ.get("FOLIO_WORDMARK_FONT", os.path.expanduser("~/Library/Fonts/Geist-Medium.otf"))
os.makedirs(os.path.join(BRAND, "concepts"), exist_ok=True)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)


def rasterise(svg_text, px, out, flatten=None):
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as fh:
        fh.write(svg_text)
    subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), fh.name, "-o", out], check=True)
    os.unlink(fh.name)
    if flatten:
        im = Image.open(out).convert("RGBA")
        bg = Image.new("RGBA", im.size, flatten)
        bg.alpha_composite(im)
        bg.convert("RGB").save(out, optimize=True)
    else:
        Image.open(out).save(out, optimize=True)


def paths_svg(name, fill):
    return "".join(f'<path fill="{fill}" d="{d}"/>' for d in mark_paths(name))


# 1. Concept masters (full 108 dp adaptive grid, background + mark)
for name in CONCEPTS:
    write(os.path.join(BRAND, "concepts", f"folio-concept-{name.lower()}.svg"), svg(name))

c = CONCEPTS[CHOSEN]
mark = paths_svg(CHOSEN, c["fg"])

# 2. Logo mark: the visible 72 dp of the icon as a rounded tile
logo = (f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="18 18 72 72">'
        f'<rect x="18" y="18" width="72" height="72" rx="16" fill="{c["bg"]}"/>{mark}</svg>\n')
write(os.path.join(BRAND, "folio-logo.svg"), logo)


# 3. Wordmark: tile + "Folio" outlined from the font
def wordmark():
    from fontTools.ttLib import TTFont
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    font = TTFont(FONT)
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    upm = font["head"].unitsPerEm
    cap = getattr(font["OS/2"], "sCapHeight", 0) or 0.7 * upm
    scale = 30 / cap  # cap height 30 units, centred on the 72-unit tile
    x, base, track = 102.0, 69.0, 0.6
    parts = []
    for ch in "Folio":
        g = cmap[ord(ch)]
        pen = SVGPathPen(gs)
        gs[g].draw(TransformPen(pen, (scale, 0, 0, -scale, x, base)))
        parts.append(pen.getCommands())
        x += hmtx[g][0] * scale + track
    width = x - track + 4
    d = "".join(parts)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width * 4:.0f}" height="{(72 + 12) * 4}" '
            f'viewBox="12 12 {width - 12:.1f} 84">'
            f'<rect x="18" y="18" width="72" height="72" rx="16" fill="{c["bg"]}"/>{mark}'
            f'<path fill="{INK}" d="{d}"/></svg>\n')


try:
    write(os.path.join(BRAND, "folio-logo-wordmark.svg"), wordmark())
except Exception as exc:  # fontTools or the font missing: keep the old file
    print("wordmark skipped:", exc)

# 4. Play Store icon: 512 px, opaque, full bleed (Play applies its own mask)
play = (f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="14 14 80 80">'
        f'<rect x="0" y="0" width="108" height="108" fill="{c["bg"]}"/>{mark}</svg>')
rasterise(play, 512, os.path.join(BRAND, "folio-play-store-512.png"), flatten=c["bg"])

# 5. Android adaptive icon layers (VectorDrawable, 108 dp)
def vector(body):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by packages/brand/tools/export.py. Folio brush F. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f'{body}</vector>\n')


fg_body = "".join(f'    <path\n        android:fillColor="{c["fg"]}"\n        android:pathData="{d}" />\n'
                  for d in mark_paths(CHOSEN))
mono_body = "".join(f'    <path\n        android:fillColor="#FF000000"\n        android:pathData="{d}" />\n'
                    for d in mark_paths(CHOSEN))
write(os.path.join(RES, "drawable/ic_launcher_foreground.xml"), vector(fg_body))
write(os.path.join(RES, "drawable/ic_launcher_monochrome.xml"), vector(mono_body))
write(os.path.join(RES, "drawable/ic_launcher_background.xml"),
      vector(f'    <path\n        android:fillColor="{c["bg"]}"\n        android:pathData="M0,0h108v108h-108z" />\n'))
adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n')
write(os.path.join(RES, "mipmap-anydpi-v26/ic_launcher.xml"), adaptive)
write(os.path.join(RES, "mipmap-anydpi-v26/ic_launcher_round.xml"), adaptive)

# 6. Legacy PNG mipmaps for API 25 (48 dp: 2 dp margin around a 44 dp shape)
legacy_square = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="14.73 14.73 78.55 78.55">'
                 f'<rect x="18" y="18" width="72" height="72" rx="12" fill="{c["bg"]}"/>{mark}</svg>')
legacy_round = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="14.73 14.73 78.55 78.55">'
                f'<circle cx="54" cy="54" r="36" fill="{c["bg"]}"/>{mark}</svg>')
for dpi, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
    folder = os.path.join(RES, f"mipmap-{dpi}")
    os.makedirs(folder, exist_ok=True)
    for stale in ("ic_launcher.webp", "ic_launcher_round.webp"):
        if os.path.exists(os.path.join(folder, stale)):
            os.remove(os.path.join(folder, stale))
    rasterise(legacy_square, px, os.path.join(folder, "ic_launcher.png"))
    rasterise(legacy_round, px, os.path.join(folder, "ic_launcher_round.png"))

print("done")
